package com.rnpc.inventory.service;

import com.rnpc.inventory.entity.Client;
import com.rnpc.inventory.entity.RepairRecord;
import com.rnpc.inventory.entity.RepairRecord.RepairStatus;
import org.apache.pdfbox.Loader;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.pdmodel.common.PDRectangle;
import org.apache.pdfbox.text.PDFTextStripper;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.text.SimpleDateFormat;
import java.util.regex.Pattern;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The client copy PDF (batch P1). The generated bytes are read back with PDFTextStripper, so these
 * check what a person would see in the PDF, not the drawing calls. No Spring context, no database.
 */
class ClientCopyPdfServiceTest {

    private final ClientCopyPdfService service = new ClientCopyPdfService();

    private static Client client() {
        Client c = new Client();
        c.setClientId(1L);
        c.setFullName("Nand Test");
        c.setContactNumber("0999 123 4567");
        return c;
    }

    private static RepairRecord repair(RepairStatus status, double cost) throws Exception {
        RepairRecord r = new RepairRecord();
        r.setRepairId(15L);
        r.setJobOrderNumber("JO-00015");
        r.setClient(client());
        r.setDeviceType("Laptop");
        r.setBrand("Acer");
        r.setModelName("Aspire 5");
        r.setIssueDescription("no display");
        r.setRepairDate(new SimpleDateFormat("yyyy-MM-dd").parse("2026-10-03"));
        r.setStatus(status);
        r.setCost(cost);
        return r;
    }

    private static String text(byte[] pdf) throws IOException {
        try (PDDocument document = Loader.loadPDF(pdf)) {
            return new PDFTextStripper().getText(document).replaceAll("\\s+", " ");
        }
    }

    private String textOf(RepairRecord r) throws IOException {
        return text(service.render(r));
    }

    private static boolean mentionsNull(String text) {
        return Pattern.compile("\\bnull\\b", Pattern.CASE_INSENSITIVE).matcher(text).find();
    }

    // ---- The document itself ------------------------------------------------------------------------

    @Test
    void itIsAnA5PortraitPdfTitledWithTheJobOrder() throws Exception {
        byte[] pdf = service.render(repair(RepairStatus.PENDING, 0));

        assertEquals("%PDF", new String(pdf, 0, 4, java.nio.charset.StandardCharsets.US_ASCII));
        try (PDDocument document = Loader.loadPDF(pdf)) {
            assertEquals(1, document.getNumberOfPages());
            PDRectangle box = document.getPage(0).getMediaBox();
            assertEquals(PDRectangle.A5.getWidth(), box.getWidth(), 0.01);
            assertEquals(PDRectangle.A5.getHeight(), box.getHeight(), 0.01);
            assertTrue(box.getHeight() > box.getWidth(), "portrait");
            assertEquals("JO-00015 client copy", document.getDocumentInformation().getTitle());
            assertTrue(document.getDocumentCatalog().getViewerPreferences().displayDocTitle());
        }
    }

    @Test
    void theFileNameIsTheJobOrderAndIsSafe() throws Exception {
        assertEquals("JO-00015.pdf", ClientCopyPdfService.fileName(repair(RepairStatus.PENDING, 0)));

        RepairRecord odd = repair(RepairStatus.PENDING, 0);
        odd.setJobOrderNumber("JO 15/\"x\"\r\n");
        assertEquals("JO_15__x_.pdf", ClientCopyPdfService.fileName(odd));

        RepairRecord none = repair(RepairStatus.PENDING, 0);
        none.setJobOrderNumber(null);
        assertEquals("client-copy.pdf", ClientCopyPdfService.fileName(none));
        assertEquals("Client copy", ClientCopyPdfService.title(none));
    }

    // ---- Content mirrors the slip -----------------------------------------------------------------

    @Test
    void itCarriesEverythingTheSlipPrints() throws Exception {
        RepairRecord r = repair(RepairStatus.COMPLETED, 2500);
        r.setSerialNumber("SN-123");
        r.setFix("Replaced the display cable");
        r.setRecommendation("Back up your files");
        r.setTechnician("Juan Dela Cruz");
        r.setWarrantyEndDate(new SimpleDateFormat("yyyy-MM-dd").parse("2027-01-05"));

        String text = textOf(r);

        for (String expected : new String[]{
                "RNPC Repair Shop", "PC and Cellphone Repair Shop",
                "JO-00015", "Oct 3, 2026",
                "CLIENT", "Nand Test", "0999 123 4567",
                "DEVICE", "Laptop - Acer Aspire 5", "SN-123",
                "REPORTED ISSUE", "no display",
                "FIX APPLIED", "Replaced the display cable",
                "RECOMMENDATION", "Back up your files",
                "Technician", "Juan Dela Cruz",
                "Estimated cost", "Php 2,500.00",
                "Status", "Completed",
                "Warranty ends", "Jan 5, 2027",
                "Please present this slip when claiming your item.",
                "Client signature", "Received by"}) {
            assertTrue(text.contains(expected), "missing [" + expected + "] in: " + text);
        }
        assertFalse(text.contains("diagnostic fee"), text);
        assertFalse(text.contains("COMPLETED"), "status is in words, not the enum: " + text);
    }

    @Test
    void aBlankSerialReadsNotRecordedAndEmptyOptionalSectionsAreLeftOut() throws Exception {
        for (String blank : new String[]{null, "", "   "}) {
            RepairRecord r = repair(RepairStatus.PENDING, 0);
            r.setSerialNumber(blank);
            r.setFix(blank);
            r.setRecommendation(blank);
            r.setTechnician(blank);

            String text = textOf(r);

            assertTrue(text.contains("Not recorded"), "[" + blank + "] " + text);
            assertFalse(text.contains("FIX APPLIED"), text);
            assertFalse(text.contains("RECOMMENDATION"), text);
            assertFalse(text.contains("Technician"), text);
            assertFalse(text.contains("Warranty ends"), text);
        }
    }

    @Test
    void theShopOnlyRemarksAreNeverPrinted() throws Exception {
        RepairRecord r = repair(RepairStatus.COMPLETED, 800);
        r.setRemarks("SHOP-ONLY-REMARK-XYZ customer is rude");
        r.setFix("Replaced the display cable");

        String text = textOf(r);

        assertFalse(text.contains("SHOP-ONLY-REMARK-XYZ"), text);
        assertFalse(text.toLowerCase().contains("remark"), text);
        assertTrue(text.contains("Replaced the display cable"), text);
    }

    // ---- Cost and status wording (the AdminRepairView helpers) ---------------------------------------

    @Test
    void anUnassessedRepairReadsToBeAssessedNeverPhpZero() throws Exception {
        for (RepairStatus status : new RepairStatus[]{RepairStatus.PENDING, RepairStatus.IN_PROGRESS}) {
            String text = textOf(repair(status, 0));

            assertTrue(text.contains("To be assessed"), status + ": " + text);
            assertFalse(text.contains("Php 0.00"), status + ": " + text);
        }
    }

    @Test
    void aCancelledRepairWithACostShowsItAsTheDiagnosticFee() throws Exception {
        String text = textOf(repair(RepairStatus.CANCELLED, 1500));

        assertTrue(text.contains("Php 1,500.00 (diagnostic fee)"), text);
        assertTrue(text.contains("Cancelled"), text);
        assertFalse(text.contains("To be assessed"), text);
    }

    @Test
    void aCancelledRepairWithNoCostShowsADashNotToBeAssessed() throws Exception {
        String text = textOf(repair(RepairStatus.CANCELLED, 0));

        assertTrue(text.contains("Estimated cost —"), text);
        assertFalse(text.contains("To be assessed"), text);
        assertFalse(text.contains("diagnostic fee"), text);
        assertFalse(text.contains("Php 0.00"), text);
    }

    @Test
    void theStatusIsSpelledInWordsForEveryStatus() throws Exception {
        String[][] expected = {{"PENDING", "Pending"}, {"IN_PROGRESS", "In Progress"}, {"COMPLETED", "Completed"},
                {"RELEASED", "Released"}, {"CANCELLED", "Cancelled"}};
        for (String[] pair : expected) {
            String text = textOf(repair(RepairStatus.valueOf(pair[0]), 100));

            assertTrue(text.contains("Status " + pair[1]), pair[0] + ": " + text);
            assertFalse(text.contains(pair[0].replace('_', ' ')) && !pair[0].equals(pair[1]), pair[0] + ": " + text);
        }
    }

    // ---- Never "null", never a failure ------------------------------------------------------------

    @Test
    void aRecordWithEverythingMissingStillRendersWithoutTheWordNull() throws Exception {
        RepairRecord bare = new RepairRecord();
        bare.setStatus(RepairStatus.PENDING);
        Client unnamed = new Client();
        bare.setClient(unnamed);

        String text = textOf(bare);

        assertFalse(mentionsNull(text), text);
        assertTrue(text.contains("Not recorded"), text);
        assertTrue(text.contains("To be assessed"), text);

        RepairRecord noClient = new RepairRecord();
        noClient.setStatus(RepairStatus.RELEASED);
        assertFalse(mentionsNull(textOf(noClient)));

        RepairRecord noStatus = new RepairRecord();
        assertFalse(mentionsNull(textOf(noStatus)));
    }

    @Test
    void aBlankBrandOrModelLeavesNoDanglingSeparator() throws Exception {
        RepairRecord r = repair(RepairStatus.PENDING, 0);
        r.setBrand(null);
        r.setModelName("  ");

        String text = textOf(r);

        assertTrue(text.contains("Item Laptop"), text);
        assertFalse(text.contains("Laptop -"), text);
        assertFalse(text.contains("()"), text);
    }

    @Test
    void charactersTheStandardFontsCannotEncodeBecomeQuestionMarksAndNothingFails() throws Exception {
        RepairRecord r = repair(RepairStatus.PENDING, 0);
        r.getClient().setFullName("Peña ₱ Привет 😀 中");
        r.setIssueDescription("Screen “flickers” — Łukasz ​ zero-width");

        String text = textOf(r);

        // Latin-1 accents and the Windows punctuation set are kept
        assertTrue(text.contains("Peña"), text);
        assertTrue(text.contains("“flickers” —"), text);
        // everything else is "?" (one per character, an emoji counts once), not an exception
        assertTrue(text.contains("Peña ? ??????"), text);
        assertTrue(text.contains("? ?"), text);
        assertFalse(text.contains("₱"), text);
    }

    @Test
    void lineBreaksAndTabsInTheTextAreCollapsedLikeTheHtmlSlipDoes() throws Exception {
        RepairRecord r = repair(RepairStatus.PENDING, 0);
        r.setIssueDescription("line one\r\nline two\n\n\tline three");

        assertTrue(textOf(r).contains("line one line two line three"));
    }

    @Test
    void aVeryLongIssueWithAnUnbreakableWordSpillsOntoMorePagesInsteadOfFailing() throws Exception {
        RepairRecord r = repair(RepairStatus.PENDING, 0);
        r.setIssueDescription(("word ".repeat(400)) + "x".repeat(300));
        r.setFix("fix ".repeat(200));
        r.setRecommendation("advice ".repeat(100));

        byte[] pdf = service.render(r);

        try (PDDocument document = Loader.loadPDF(pdf)) {
            assertTrue(document.getNumberOfPages() > 1);
        }
        String text = text(pdf);
        // the signatures still close the document
        assertTrue(text.contains("Client signature") && text.contains("Received by"), text);
        assertNotNull(text);
    }
}
